// Rebuilds data/law/sources.json from the ledgers and their snapshot records: for each cited URL, the
// statutes it backs, the extraction method, the text hash and the date fetched. Run after each state.
//   node scripts/law-sources.mjs
import fs from 'node:fs';
import path from 'node:path';
import { loadSnapshot } from '../../foundry/tools/law-text.mjs';
import { LAW, ROOT } from './law-pieces.mjs';

const sources = {};
for (const f of fs.readdirSync(LAW).filter((n) => /^[a-z]{2}\.json$/.test(n)).sort()) {
  const L = JSON.parse(fs.readFileSync(path.join(LAW, f), 'utf8'));
  for (const c of L.claims || []) {
    if (!c.url || !c.snapshot || c.lang !== 'en') continue;
    const snap = loadSnapshot(path.join(ROOT, c.snapshot));
    if (!snap.ok) continue;
    const e = sources[c.url] || (sources[c.url] = { state: f.slice(0, 2).toUpperCase(), statutes: [], extractor: snap.meta.extractor, text_sha256: snap.meta.text_sha256, fetched_at: snap.meta.fetched_at, snapshot: c.snapshot });
    if (!e.statutes.includes(c.statute)) e.statutes.push(c.statute);
  }
}
fs.writeFileSync(path.join(LAW, 'sources.json'), JSON.stringify({ note: 'Generated by scripts/law-sources.mjs. Used by scripts/watch-statutes.mjs.', sources }, null, 1) + '\n');
console.log(`sources.json: ${Object.keys(sources).length} URLs`);
